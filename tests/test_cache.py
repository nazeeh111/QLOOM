"""Cache admission uses real compilation and independent output oracles."""

import hashlib
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from unittest.mock import patch

import numpy as np
import pytest
from qiskit import QuantumCircuit, qasm2
from qiskit.quantum_info import Operator

from qloom.circuits import load_qasm, operations, split_circuit
from qloom.compiler import compile_circuit
from qloom.devices import make_device

OPTIONS = dict(budget=2, strategy="heuristic", baselines=False, noisy=False)


def circuit():
    qc = QuantumCircuit(4, 7)
    qc.ry(0.37, 0)
    qc.rx(-0.82, 2)
    qc.cx(0, 3)
    qc.p(0.113, 1)
    qc.cx(3, 2)
    qc.global_phase = 0.741
    qc.measure(3, 1)
    qc.measure(0, 6)
    return qc


def rewrite(path, entry):
    # Rehashed edits must still pass semantic admission, not merely a checksum.
    entry["report_sha256"] = hashlib.sha256(
        json.dumps(entry["report"], sort_keys=True, allow_nan=False).encode()
    ).hexdigest()
    path.write_text(json.dumps(entry))


def assert_oracle(qc, report):
    reference, measurements = split_circuit(qc)
    expected = Operator(reference).data
    for c in report["candidates"]:
        exported = load_qasm(c["qasm"], max_operations=None)
        physical, measured = split_circuit(exported, max_operations=None)
        physical.global_phase = c["global_phase"]
        pin = [
            sum(((x >> q) & 1) << p for q, p in enumerate(c["initial_mapping"]))
            for x in range(1 << qc.num_qubits)
        ]
        pout = [
            sum(((x >> q) & 1) << p for q, p in enumerate(c["final_mapping"]))
            for x in range(1 << qc.num_qubits)
        ]
        matrix = Operator(physical).data
        np.testing.assert_allclose(matrix[np.ix_(pout, pin)], expected, rtol=0, atol=1e-12)
        # Exhaust every computational-basis input; preserve sparse classical bits.
        actual_probs = np.zeros((1 << qc.num_clbits, 1 << qc.num_qubits))
        expected_probs = np.zeros_like(actual_probs)
        for x in range(1 << qc.num_qubits):
            actual_bits = sum(((x >> q) & 1) << b for q, b in measured)
            expected_bits = sum(((x >> q) & 1) << b for q, b in measurements)
            actual_probs[actual_bits] += abs(matrix[x, pin]) ** 2
            expected_probs[expected_bits] += abs(expected[x]) ** 2
        np.testing.assert_allclose(actual_probs, expected_probs, rtol=0, atol=1e-12)


def test_cold_warm_exact_output_and_current_display_name(tmp_path):
    qc = circuit()
    cold = compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    qc.name = "current caller"
    with patch("qloom.compiler.native_compile", side_effect=AssertionError("Warm hit recompiled")):
        warm = compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    assert warm["cache_hit"] and warm["cache"]["status"] == "verified-hit"
    assert warm["input"]["name"] == "current caller"
    assert warm["candidates"] == cold["candidates"]
    assert warm["cache"]["lookup_verification_s"] >= 0
    assert_oracle(qc, cold)
    assert_oracle(qc, warm)


def test_raw_qasm_autogenerated_names_and_register_spelling_reuse(tmp_path):
    source = qasm2.dumps(circuit())
    first = compile_circuit(source, cache_dir=tmp_path, **OPTIONS)
    second = compile_circuit(source, cache_dir=tmp_path, **OPTIONS)
    renamed = compile_circuit(source.replace("q[", "other["), cache_dir=tmp_path, **OPTIONS)
    assert first["input"]["name"] != second["input"]["name"]
    assert not first["cache_hit"] and second["cache_hit"] and renamed["cache_hit"]
    assert len(list(tmp_path.glob("*.json"))) == 1


@pytest.mark.parametrize("change", ["gate", "phase", "measurement", "width", "device", "seed", "budget", "strategy"])
def test_semantic_and_request_changes_do_not_alias(tmp_path, change):
    qc = circuit()
    compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    options = dict(OPTIONS)
    if change == "gate":
        from qiskit.circuit.library import RYGate
        qc.data[0] = qc.data[0].replace(operation=RYGate(0.9))
    elif change == "phase":
        qc.global_phase += 0.1
    elif change == "measurement":
        qc.data[-1] = qc.data[-1].replace(clbits=[qc.clbits[5]])
    elif change == "width":
        qc = QuantumCircuit(3)
        qc.h(0)
    elif change == "device":
        options["device"] = make_device("ring", 4)
    elif change == "seed":
        options["seed"] = 4
    elif change == "budget":
        options["budget"] = 1
    else:
        options["strategy"] = "random"
    assert not compile_circuit(qc, cache_dir=tmp_path, **options)["cache_hit"]
    assert len(list(tmp_path.glob("*.json"))) == 2


@pytest.mark.parametrize("mutation", [
    "qasm", "phase", "initial", "final", "operations", "classical", "passed",
    "measurement_passed", "metrics", "best", "pareto", "input", "schema",
    "implementation", "count", "shape", "nan", "truncated", "checksum", "old",
    "coherent_wrong_gate", "phase_type", "qasm_type", "noise_metadata", "model_metadata", "export_note",
])
def test_corrupt_cache_is_diagnosed_and_recomputed(tmp_path, mutation):
    qc = circuit()
    cold = compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    path = next(tmp_path.glob("*.json"))
    entry = json.loads(path.read_text())
    r = entry["report"]
    c = r["candidates"][0]
    if mutation == "qasm":
        c["qasm"] = "invalid QASM"
    elif mutation == "qasm_type":
        c["qasm"] = None
    elif mutation == "phase_type":
        c["global_phase"] = "not a number"
    elif mutation == "phase":
        c["global_phase"] += 0.1
    elif mutation in ("initial", "final"):
        m = c[mutation + "_mapping"]
        m[0], m[1] = m[1], m[0]
    elif mutation == "operations":
        c["operations"][0]["params"][0] += 0.2
    elif mutation == "classical":
        c["qasm"] = c["qasm"].replace("-> c[1]", "-> c[2]")
    elif mutation == "passed":
        c["verification"]["passed"] = False
    elif mutation == "measurement_passed":
        c["verification"]["measurement_passed"] = False
    elif mutation == "metrics":
        c["metrics"]["objective"] = -1
    elif mutation == "best":
        r["best_id"] = "missing"
    elif mutation == "pareto":
        r["pareto_ids"] = []
    elif mutation == "input":
        r["input"]["global_phase"] += 0.1
    elif mutation == "noise_metadata":
        r["noise"] = {"method": "fabricated", "fidelity": 999}
    elif mutation == "model_metadata":
        r["model"] = {"name": "fabricated"}
    elif mutation == "export_note":
        r["export_note"] = "wrong"
    elif mutation == "schema":
        entry["schema"] = 999
    elif mutation == "implementation":
        entry["request"]["implementation"]["source"]["verify.py"] = "stale"
    elif mutation == "count":
        r["candidates"].pop()
    elif mutation == "shape":
        c["initial_mapping"] = None
    elif mutation == "coherent_wrong_gate":
        exported = load_qasm(c["qasm"], max_operations=None)
        physical, measures = split_circuit(exported, max_operations=None)
        physical.u(0.3, 0.2, 0.1, 0)
        from qloom.circuits import export_qasm
        # The edit is internally consistent; only exact semantics rejects it.
        c["operations"] = operations(physical)
        c["qasm"] = export_qasm(physical, measures, list(range(4)), 7)
        c["verification"]["tolerance"] = 1000
    if mutation == "nan":
        path.write_text(path.read_text().replace('"elapsed_s":', '"elapsed_s": NaN, "unused":', 1))
    elif mutation == "truncated":
        path.write_text('{"schema":')
    elif mutation == "old":
        path.write_text(json.dumps(r))
    elif mutation == "checksum":
        c["global_phase"] += 0.1
        path.write_text(json.dumps(entry))
    else:
        rewrite(path, entry)
    repaired = compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    assert not repaired["cache_hit"], mutation
    assert repaired["cache"]["status"] == "rejected", mutation
    for a, b in zip(cold["candidates"], repaired["candidates"]):
        for key in ("operations", "qasm", "global_phase", "initial_mapping", "final_mapping"):
            assert a[key] == b[key], (mutation, key)
    assert_oracle(qc, repaired)
    assert compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)["cache_hit"]


def test_same_key_concurrent_writers_publish_complete_generation(tmp_path):
    qc = circuit()
    with ThreadPoolExecutor(max_workers=2) as executor:
        results = list(executor.map(lambda _: compile_circuit(qc, cache_dir=tmp_path, **OPTIONS), range(2)))
    for result in results:
        assert_oracle(qc, result)
    assert compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)["cache_hit"]
    assert len(list(tmp_path.glob("*.json"))) == 1
    assert not list(tmp_path.glob("*.tmp"))


def test_eight_qubit_cache_keeps_full_operator_check(tmp_path):
    qc = QuantumCircuit(8)
    qc.global_phase = 0.29
    qc.ry(0.3, 6)
    qc.cx(6, 0)
    compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    report = compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    assert report["cache_hit"]
    assert_oracle(qc, report)
    path = next(tmp_path.glob("*.json"))
    entry = json.loads(path.read_text())
    entry["report"]["candidates"][0]["global_phase"] += 0.02
    rewrite(path, entry)
    assert compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)["cache"]["status"] == "rejected"


