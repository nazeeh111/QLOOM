def test_cache_write_failure_keeps_previous_entry_and_valid_result(tmp_path):
    qc = circuit()
    compile_circuit(qc, cache_dir=tmp_path, **OPTIONS)
    path = next(tmp_path.glob("*.json"))
    original = path.read_bytes()
    from qloom.cache import write_report
    entry = json.loads(original)
    with patch.object(Path, "replace", side_effect=OSError("injected publication failure")):
        with pytest.raises(OSError):
            write_report(path, entry["request"], entry["report"])
    assert path.read_bytes() == original
    assert not list(tmp_path.glob("*.tmp"))
    with patch("qloom.compiler.write_report", side_effect=OSError("unwritable cache")):
        result = compile_circuit(qc, cache_dir=tmp_path / "other", **OPTIONS)
    assert "write_error" in result["cache"]
    assert_oracle(qc, result)


def test_real_cli_cold_warm_corrupt_fallback_exports(tmp_path):
    source = tmp_path / "input.qasm"
    source.write_text(qasm2.dumps(circuit()))
    cache = tmp_path / "cache"
    command = [
        sys.executable, "-m", "qloom.cli", "compile", str(source), "--device", "line-4",
        "--strategy", "heuristic", "--budget", "2", "--skip-baselines", "--skip-noise",
        "--cache", str(cache),
    ]
    env = dict(os.environ, PYTHONPATH=str(Path(__file__).parents[1] / "src"))
    for index in range(3):
        out = tmp_path / f"bundle-{index}"
        if index == 2:
            next(cache.glob("*.json")).write_text("{truncated")
        proc = subprocess.run(command + ["--out", str(out)], env=env, text=True, capture_output=True)
        assert proc.returncode == 0, proc.stderr
        report = json.loads((out / "report.json").read_text())
        assert report["cache_hit"] == (index == 1)
        assert_oracle(load_qasm(source.read_text()), report)
        best = next(c for c in report["candidates"] if c["id"] == report["best_id"])
        assert (out / "optimized.qasm").read_text().strip() == best["qasm"].strip()
        assert json.loads((out / "metadata.json").read_text())["verification"]["passed"]
        if index == 2:
            assert "Cache rejected; recomputed:" in proc.stdout


def test_historical_noise_observation_validation():
    from copy import deepcopy
    from qloom.cache import validate_noise
    from qloom.report_policy import NOISE_ASSUMPTIONS, NOISE_METHOD

    qc = QuantumCircuit(2)
    qc.h(0)
    reference, measurements = split_circuit(qc)
    request = {"noisy": True}
    baselines = [{"id": "qiskit-0", "status": "ok"}]
    valid = {"method": NOISE_METHOD, "assumptions": NOISE_ASSUMPTIONS,
             "ideal_probabilities": [0.5, 0.5, 0.0, 0.0],
             "optimized_probabilities": [0.5, 0.5, 0.0, 0.0],
             "input_probabilities": [0.5, 0.5, 0.0, 0.0],
             "optimized_fidelity": 1.0, "input_fidelity": 1.0}
    validate_noise(valid, request, reference, measurements, 0, baselines)
    for field, value in [("optimized_fidelity", 0.1), ("input_fidelity", 999),
                         ("ideal_probabilities", [1.0, 0.0, 0.0, 0.0]),
                         ("optimized_probabilities", [0.6, 0.6, 0.0, 0.0]),
                         ("method", "invented")]:
        bad = deepcopy(valid)
        bad[field] = value
        with pytest.raises(ValueError):
            validate_noise(bad, request, reference, measurements, 0, baselines)
